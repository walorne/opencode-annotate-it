import { Schema } from "effect"
import { Plugin, Store } from "@opencode/plugin/gui"

/** One editable quick reply: `label` is the chip, `text` the phrase attached to the quote. */
export const QuickAction = Schema.Struct({
  id: Schema.String,
  label: Schema.String,
  text: Schema.String,
})
export type QuickAction = typeof QuickAction.Type

/** A chat anchor piece: exact offsets inside a stable timeline part (same shape the app itself uses). */
export const ChatPiece = Schema.Struct({
  partID: Schema.String,
  revealID: Schema.String,
  body: Schema.optional(Schema.String),
  start: Schema.Number,
  end: Schema.Number,
  text: Schema.String,
})
export type ChatPiece = typeof ChatPiece.Type

/** A document anchor: the quoted text plus surrounding context, re-found by text after a re-render. */
export const DocAnchor = Schema.Struct({
  path: Schema.String,
  text: Schema.String,
  prefix: Schema.String,
  suffix: Schema.String,
})
export type DocAnchor = typeof DocAnchor.Type

export const NoteSource = Schema.Union([
  Schema.Struct({ kind: Schema.Literal("chat") }),
  Schema.Struct({ kind: Schema.Literal("document"), path: Schema.String }),
])
export type NoteSource = typeof NoteSource.Type

export const NoteComment = Schema.Struct({
  text: Schema.String,
  sent: Schema.Boolean,
})
export type NoteComment = typeof NoteComment.Type

/** One annotated passage with its comment history. Lives per session. */
export const Note = Schema.Struct({
  id: Schema.String,
  quote: Schema.String,
  source: NoteSource,
  chat: Schema.optional(Schema.Array(ChatPiece)),
  doc: Schema.optional(DocAnchor),
  comments: Schema.Array(NoteComment),
  created: Schema.Number,
})
export type Note = typeof Note.Type

